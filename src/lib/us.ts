export function stateFromZip(zip: string): string | null {
  const digits = zip.replace(/\D/g, "");
  if (digits.length < 3) return null;
  const p = Number(digits.slice(0, 3));
  return ZIP3.find(([lo, hi]) => p >= lo && p <= hi)?.[2] ?? null;
}

/** "4111111111111111" → "4111 1111 1111 1111" (display only; nothing is stored). */
export function formatCard(v: string) {
  return v.replace(/\D/g, "").slice(0, 19).replace(/(.{4})(?=.)/g, "$1 ");
}

/** "1228" → "12 / 28" */
export function formatExpiry(v: string) {
  const d = v.replace(/\D/g, "").slice(0, 4);
  return d.length > 2 ? `${d.slice(0, 2)} / ${d.slice(2)}` : d;
}
